/** Bake a uniform scale plus translate into a path so it needs no transform attribute. */
function bake(path, { scale = 1, tx = 0, ty = 0 }) {
  const segs = parsePath(path)
  return segs
    .map((seg, i) => {
      const [cmd, ...nums] = seg
      const absolute = cmd === cmd.toUpperCase() || i === 0
      const out = nums.map((n, j) => {
        const isX = j % 2 === 0
        return +(n * scale + (absolute ? (isX ? tx : ty) : 0)).toFixed(3)
      })
      return cmd + out.join(' ')
    })
    .join('')
}

