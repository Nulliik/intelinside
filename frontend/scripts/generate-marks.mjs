/** Near-black brand colours become currentColor, which the components resolve to the foreground on the dark ground. */
function brandFill(hex) {
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
  const lum = 0.2126 * r + 0.7152 * g + 0.0722 * b
  return lum < 0.2 ? 'currentColor' : '#' + hex.toLowerCase()
}

function entry(title, paths, fallbackBox = '0 0 24 24') {
  const all = paths.map((p) => p.d).join(' ')
  try {
    const [x0, y0, x1, y1] = bounds(all)
    const w = x1 - x0, h = y1 - y0
    return { title, viewBox: `${x0.toFixed(3)} ${y0.toFixed(3)} ${w.toFixed(3)} ${h.toFixed(3)}`, ratio: +(w / h).toFixed(3), paths }
  } catch {
    console.warn(`${title}: path parser rejected it, using ${fallbackBox}`)
    const [, , w, h] = fallbackBox.split(' ').map(Number)
    return { title, viewBox: fallbackBox, ratio: +(w / h).toFixed(3), paths }
  }
}
